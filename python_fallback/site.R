# Separate Stage 2 route. No Stage 1 caches and no R Arrow installation needed.
source('python_fallback/environment.R');clif_fallback_check_environment()
source('scripts/deployment_lib.R')
a<-commandArgs(trailingOnly=TRUE)
if(length(a)!=2L||!a[1]%in%c('stage2-preflight','stage2'))stop('Usage: Rscript --vanilla python_fallback/site.R stage2-preflight|stage2 config/config.json')
config<-normalizePath(a[2],mustWork=TRUE);cfg<-deploy_config(config)
release<-jsonlite::fromJSON('python_fallback/release.json',simplifyVector=FALSE)
parent<-deploy_validate_inventory('frozen/stage2_v1','bundle_manifest.json')
if(!identical(deploy_hash(),release$parent_source_hash)||!identical(parent$source_hash,release$parent_source_hash)||!identical(deploy_lock_hash(),release$r_lock_md5))stop('Restore the coordinator-issued source and renv.lock before using the fallback. R Arrow itself may be any version or absent.')
probe<-system2(cfg$python,c(shQuote('scripts/python_preflight.py')),stdout=TRUE,stderr=TRUE)
if(!is.null(attr(probe,'status')))stop('Pinned Python environment failed: ',paste(probe,collapse='\n'))
probe<-system2(cfg$python,c(shQuote('python_fallback/parquet_bridge.py'),'--probe'),stdout=TRUE,stderr=TRUE)
if(!is.null(attr(probe,'status')))stop('Python Parquet/Dataset read-write probe failed: ',paste(probe,collapse='\n'))
cat('Python Parquet/Dataset read-write probe: ',paste(probe,collapse='\n'),'\n',sep='')
out<-Sys.getenv('CLIF_FALLBACK_OUTPUT',unset=file.path(clif_root,'output',paste0('run_',cfg$site_name,'_stage2_python_v1')))
dir.create(file.path(out,'local'),recursive=TRUE,showWarnings=FALSE);out<-normalizePath(out)
buildlog<-file.path(out,'local/build_pipeline.log')
status<-system2(cfg$python,c(shQuote('python_fallback/build_pipeline.py'),shQuote(clif_root),shQuote(config),shQuote(out)),stdout=buildlog,stderr=buildlog)
if(status!=0)stop('Fallback workspace failed to build. Inspect ',buildlog)
workspace<-file.path(out,'local/pipeline')
Sys.setenv(CLIF_FALLBACK_REPO=clif_root,CLIF_FALLBACK_RUN_ROOT=out,CLIF_FALLBACK_PYTHON=cfg$python)
old<-getwd()
status<-tryCatch({setwd(workspace);system2(file.path(R.home('bin'),'Rscript'),c('--vanilla','scripts/site.R',a[1],'config/config.json','frozen/stage2_python_v1'))},finally=setwd(old))
if(status!=0)stop('Python fallback failed; inspect the worker log printed above. Rerun this same fallback command to resume completed steps.')
if(a[1]=='stage2'){
 ret<-file.path(out,'analysis/stage2_return');m<-deploy_validate_inventory(ret)
 m$python_fallback<-list(release='stage2_python_v1',parquet_backend='pyarrow',r_arrow_required=FALSE,parent_bundle_md5=release$parent_bundle_md5,parent_source_hash=release$parent_source_hash,effective_source_hash=release$effective_source_hash,host_timezone=Sys.timezone(),legacy_timestamp_semantics_preserved=TRUE)
 deploy_json(m,file.path(ret,'return_manifest.json'));deploy_validate_inventory(ret)
 cat('\nPYTHON FALLBACK COMPLETE. Upload only: ',ret,'\n',sep='')
}

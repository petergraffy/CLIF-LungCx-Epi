source('scripts/deployment_lib.R')
scratch<-tempfile('source_contract_');dir.create(scratch)
lf<-file.path(scratch,'lf.R');crlf<-file.path(scratch,'crlf.R');changed<-file.path(scratch,'changed.R')
writeBin(charToRaw('x <- 1\n# source\n'),lf)
writeBin(charToRaw('x <- 1\r\n# source\r\n'),crlf)
writeBin(charToRaw('x <- 2\r\n# source\r\n'),changed)
stopifnot(unname(source_text_md5(lf))==unname(source_text_md5(crlf)),unname(source_text_md5(lf))!=unname(source_text_md5(changed)))
stopifnot(unname(tools::md5sum(lf))!=unname(tools::md5sum(crlf)))
# Inventory checks retain byte-level integrity and reject empty or altered uploads.
packet<-file.path(scratch,'packet');dir.create(packet)
file.copy(lf,file.path(packet,'source.txt'))
deploy_finish(packet,'stage1','SYNTHETIC')
m<-deploy_validate_inventory(packet);deploy_assert_contract(m)
stopifnot(m$source_hash_policy=='text-md5-crlf-to-lf-v1',length(m$source_files_md5)>0)
file.copy(crlf,file.path(packet,'source.txt'),overwrite=TRUE)
stopifnot(inherits(tryCatch(deploy_validate_inventory(packet),error=identity),'error'))
file.create(file.path(packet,'empty.csv'))
stopifnot(inherits(tryCatch(deploy_inventory(packet),error=identity),'error'))
bad<-m;bad$source_hash<-'changed';bad$source_files_md5[['code/lib/common.R']]<-'changed'
err<-tryCatch(deploy_assert_contract(bad),error=identity)
stopifnot(inherits(err,'error'),grepl('code/lib/common.R',conditionMessage(err),fixed=TRUE))
unlink(scratch,recursive=TRUE)
cat('PASS: cross-platform source hashes, real source changes, per-file provenance, exact artifact integrity and empty-upload rejection\n')

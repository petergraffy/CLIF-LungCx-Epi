source('diagnostics/revision20261022/lib.R');source('diagnostics/sofa_completeness/context.R')
site<-commandArgs(trailingOnly=TRUE)[1];home<-file.path(rev_root(),'sites',site)
a<-readRDS(file.path(old_root(),'sites',site,'local/discovery.rds'));d<-a$data;m<-jsonlite::fromJSON(file.path(a$input_root,'local/input_manifest.json'))
source_dir<-Sys.getenv(paste0('CLIF_SITE_TABLES_',site),unset=dirname(m$source_file))
x<-sofa_source_rows(source_dir,'labs',d$hospitalization_id)
metadata_available<-any(c('lab_name','lab_loinc_code')%in%names(x))
x<-with_columns(x,c('lab_name','lab_loinc_code'))
hit<-grepl('hct|hematocrit|haematocrit',x$lab_name,ignore.case=TRUE)|grepl('4544-3|20570-8',x$lab_loinc_code)
z<-x[which(hit),] |> dplyr::inner_join(d |> dplyr::select(hospitalization_id,t0),by='hospitalization_id')
z$lab_result_dttm<-utc(z$lab_result_dttm)
n<-length(unique(z$hospitalization_id[which(z$lab_result_dttm>=z$t0 & z$lab_result_dttm<z$t0+24*3600 & is.finite(num(z$lab_value_numeric)))]))
b<-if(metadata_available)fed_band_n(n) else c(NA_real_,NA_real_)
status<-if(!metadata_available)'source_labels_and_LOINC_unavailable' else if(n==0)'no_first24h_source_measurements_found' else 'source_label_or_LOINC_hematocrit_present'
fed_write(tibble::tibble(site=site,component='hematocrit_source_label_or_LOINC_audit',available_lower=b[1],available_upper=b[2],status=status),file.path(home,'export/severity_source_audit.csv'))

source('code/lib/load.R')
a<-commandArgs(trailingOnly=TRUE);if(length(a)!=4)stop('Usage: add_curves_to_return.R SITE CURVE_SHARE OLD_SHARE NEW_SHARE')
site<-a[1];curve<-a[2];old<-a[3];out<-a[4];if(dir.exists(out))stop('Choose fresh return')
m<-jsonlite::fromJSON(file.path(old,'site_return_manifest.json'),simplifyVector=FALSE)
cm<-jsonlite::fromJSON(file.path(curve,'curve_manifest.json'))
stopifnot(m$site==site,cm$site==site,cm$status=='passed',cm$consensus_id==m$primary_consensus_id)
stopifnot(unname(tools::md5sum(file.path(curve,'cumulative_incidence_daily.csv')))==cm$files$cumulative_incidence_daily.csv)
dir.create(out,recursive=TRUE)
for(f in list.files(old,recursive=TRUE,full.names=FALSE)){dest<-file.path(out,f);dir.create(dirname(dest),recursive=TRUE,showWarnings=FALSE);stopifnot(file.copy(file.path(old,f),dest))}
stopifnot(file.copy(file.path(curve,'cumulative_incidence_daily.csv'),file.path(out,'federated/primary/outcomes/full/cumulative_incidence_daily.csv')))
m$parent_return_manifest_md5<-unname(tools::md5sum(file.path(old,'site_return_manifest.json')))
m$daily_competing_event_curves_complete<-TRUE
f<-setdiff(list.files(out,recursive=TRUE,full.names=FALSE),'site_return_manifest.json')
m$files<-as.list(setNames(unname(tools::md5sum(file.path(out,f))),f))
jsonlite::write_json(m,file.path(out,'site_return_manifest.json'),auto_unbox=TRUE,pretty=TRUE,null='null')
